public class constants {
    
    public static void main(String[] args) {
    // A constant is a value that, once assigned, cannot be reassigned.
    // In Java, we create constants using the keyword:

    final int DAYS_IN_WEEK = 7;

    // Variable  → can change
    // Constant  → cannot be reassigned

    final int MONTHS_IN_YEAR = 12;
    final double PI = 3.14159265359;
    final String COUNTRY_NAME = "India";

    System.out.println(DAYS_IN_WEEK);
    System.out.println(MONTHS_IN_YEAR);
    System.out.println(PI);
    System.out.println
    (COUNTRY_NAME);



    }
}
